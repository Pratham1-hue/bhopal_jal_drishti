const LangContext = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('vgw-lang') || 'en')
  useEffect(() => {
    localStorage.setItem('vgw-lang', lang)
    document.documentElement.lang = lang === 'hi' ? 'hi' : 'en'
  }, [lang])
  const value = useMemo(() => {
    const dict = STRINGS[lang]
    return {
      lang,
      setLang,
      toggle: () => setLang((l) => (l === 'en' ? 'hi' : 'en')),
      t: dict,
      pick: (obj, field) => (lang === 'hi' && obj?.[`${field}_hi`] ? obj[`${field}_hi`] : obj?.[field]),
      fest: (f) => (f === 'Durga' ? dict.durga : f === 'Ganesh' ? dict.ganesh : f),
      param: (key) => PARAM_SIMPLE[lang][key] || key,
    }
  }, [lang])
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export const useLang = () => useContext(LangContext)
